// One-off generator: scopes the captured live-site stylesheet under `.universe` so it cannot collide with
// Tailwind utilities (.container) or the portal pages. Usage: node scripts/scope-universe-css.mjs <in.css> <out.css>
import fs from "node:fs";
import postcss from "postcss";

const [input, output] = process.argv.slice(2);
const root = postcss.parse(fs.readFileSync(input, "utf8"));
const SCOPE = ".universe";

function scope(selector) {
  const s = selector.trim();
  if (s === ":root" || s === "html" || s === "body") return SCOPE;
  if (/^(html|body)\s/.test(s)) return s.replace(/^(html|body)\s+/, `${SCOPE} `);
  return `${SCOPE} ${s}`;
}

root.walkRules((rule) => {
  const parent = rule.parent;
  if (parent && parent.type === "atrule" && /keyframes$/.test(parent.name)) return;
  rule.selectors = rule.selectors.map(scope);
});
// Keyframe names are global; prefix them so they cannot clash with anything else.
const names = new Set();
root.walkAtRules(/keyframes$/, (at) => { names.add(at.params); at.params = `uv-${at.params}`; });
root.walkDecls((d) => {
  if (/^animation(-name)?$/.test(d.prop)) {
    for (const n of names) d.value = d.value.replace(new RegExp(`(^|[\\s,])${n}(?=[\\s,;]|$)`, "g"), `$1uv-${n}`);
  }
});
fs.writeFileSync(output, "/* GENERATED by scripts/scope-universe-css.mjs from the captured live ezeirl.com stylesheet. Edit the source rules deliberately; keep the .universe scope. */\n" + root.toString());
console.log("rules scoped; keyframes prefixed:", [...names].join(", "));
